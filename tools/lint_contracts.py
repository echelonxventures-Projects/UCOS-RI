#!/usr/bin/env python3
"""Contract linter — CIC-005-001 §10 (ucos-api-rules), CIC-006-001 §7–9, CIC-001-001 VR-001-001-02.

Checks every contracts/**/*.openapi.yaml and *.asyncapi.yaml plus contracts/kernel/*.schema.json:
  structural   OpenAPI 3.1 validity (openapi-spec-validator); AsyncAPI 3.0 required structure;
               kernel schemas valid against JSON Schema 2020-12
  ucos rules   ucos-idempotency-key-on-post, ucos-if-match-on-mutation, ucos-problem-json-errors,
               ucos-permission-extension, ucos-no-float-money, ucos-camel-case-properties,
               ucos-path-kebab, ucos-operation-id-matches-command, event naming + context segment
               (VR-006-001-01), unique event types (VR-006-001-02), DOM coverage (CR-006-001-02)
Hand-authored contracts (no `x-ucos-source.generated`) must use x-ucos-permission, never candidates.
"""
import json
import pathlib
import re
import sys

import yaml
from jsonschema import Draft202012Validator
from openapi_spec_validator import validate
from openapi_spec_validator.readers import read_from_filename

ROOT = pathlib.Path(__file__).resolve().parent.parent
C = ROOT / "contracts"
DOMAINS = ROOT / "corpus/corpora/CORPUS-002-domain/domains"
EVENT = re.compile(r"^ucos\.([a-z0-9-]+)\.([a-z0-9-]+)\.([a-z0-9-]+)\.v[0-9]+$")
CAMEL = re.compile(r"^[a-z][a-zA-Z0-9]*$")
SEGMENT = re.compile(r"^([a-z0-9][a-z0-9-]*|\{[A-Za-z0-9_]+\})(:[a-z][a-z0-9-]*)?$|^\{[A-Za-z0-9_]+\}:[a-z][a-z0-9-]*$|^:[a-z][a-z0-9-]*$")
MUTATING = {"put", "patch", "delete"}

errors: list[str] = []


def err(path, msg):
    errors.append(f"{path.relative_to(ROOT)}: {msg}")


def walk(node, fn, ptr=""):
    if isinstance(node, dict):
        fn(node, ptr)
        for k, v in node.items():
            walk(v, fn, f"{ptr}/{k}")
    elif isinstance(node, list):
        for i, v in enumerate(node):
            walk(v, fn, f"{ptr}/{i}")


def is_generated(text):
    return text.startswith("# GENERATED by tools/gen_contracts.py")


def lint_schema_common(p, doc):
    def visit(n, ptr):
        if n.get("type") == "number" or (isinstance(n.get("type"), list) and "number" in n["type"]):
            err(p, f"ucos-no-float-money: binary number type at {ptr} (use kernel decimal)")
        props = n.get("properties")
        if isinstance(props, dict) and "/x-" not in ptr:
            for name in props:
                if not CAMEL.match(name):
                    err(p, f"ucos-camel-case-properties: '{name}' at {ptr}")
    walk(doc, visit)


def lint_openapi(p, generated):
    spec, base = read_from_filename(str(p))
    try:
        validate(spec, base_uri=f"file://{p}")
    except Exception as e:  # noqa: BLE001 — report any validator failure as a lint error
        err(p, f"OpenAPI 3.1 invalid: {str(e).splitlines()[0][:200]}")
        return
    lint_schema_common(p, spec)
    params = spec.get("components", {}).get("parameters", {})

    def has_param(op, name):
        for prm in op.get("parameters", []):
            if "$ref" in prm:
                prm = params.get(prm["$ref"].rsplit("/", 1)[-1], {})
            if prm.get("name", "").lower() == name.lower():
                return True
        return False

    for path, item in (spec.get("paths") or {}).items():
        for seg in ([] if path.startswith("/.well-known/") else path.strip("/").split("/")):  # RFC 8615 names are fixed
            if seg and not SEGMENT.match(seg):
                err(p, f"ucos-path-kebab: segment '{seg}' in {path}")
        for m, op in item.items():
            if m not in ("get", "post", "put", "patch", "delete"):
                continue
            kind = op.get("x-ucos-kind")
            where = f"{m.upper()} {path}"
            if not has_param(op, "UCOS-Tenant"):
                err(p, f"UCOS-Tenant header missing on {where}")
            if kind == "command" and m == "post" and not has_param(op, "Idempotency-Key"):
                err(p, f"ucos-idempotency-key-on-post: {where}")
            if kind == "command" and m in MUTATING and not has_param(op, "If-Match"):
                err(p, f"ucos-if-match-on-mutation: {where}")
            if "default" not in op.get("responses", {}):
                err(p, f"ucos-problem-json-errors: no default problem response on {where}")
            if "x-ucos-permission" not in op and (not generated or "x-ucos-permission-candidates" not in op):
                err(p, f"ucos-permission-extension: {where}")
            if kind == "command" and not re.match(r"^[A-Z][A-Za-z0-9]*(_.*)?$", op.get("operationId", "")):
                err(p, f"ucos-operation-id-matches-command: {op.get('operationId')} on {where}")


def lint_asyncapi(p, src_ctx, seen_types):
    doc = yaml.safe_load(p.read_text())
    if doc.get("asyncapi") != "3.0.0":
        err(p, "asyncapi must be 3.0.0")
    for key in ("info", "channels", "operations"):
        if key not in doc:
            err(p, f"AsyncAPI missing '{key}'")
    lint_schema_common(p, doc.get("components", {}))
    types = []
    for name, ch in (doc.get("channels") or {}).items():
        t = ch.get("address", "")
        m = EVENT.match(t)
        if not m:
            err(p, f"VR-000-002-02 event type '{t}' malformed")
            continue
        if src_ctx and m.group(1) != src_ctx:
            err(p, f"VR-006-001-01 event '{t}' context segment != bounded context '{src_ctx}'")
        if t in seen_types:
            err(p, f"VR-006-001-02 event '{t}' also declared in {seen_types[t]}")
        seen_types[t] = p.name
        types.append(t)
    for opname, op in (doc.get("operations") or {}).items():
        if op.get("action") not in ("send", "receive"):
            err(p, f"operation {opname} has invalid action")
    return types


def main():
    for k in sorted((C / "kernel").glob("*.schema.json")):
        try:
            Draft202012Validator.check_schema(json.loads(k.read_text()))
        except Exception as e:  # noqa: BLE001
            err(k, f"invalid JSON Schema: {e}")
    seen_types: dict[str, str] = {}
    n_oas = n_aas = 0
    for p in sorted(C.rglob("*.openapi.yaml")):
        lint_openapi(p, is_generated(p.read_text()))
        n_oas += 1
    for p in sorted(C.rglob("*.asyncapi.yaml")):
        doc = yaml.safe_load(p.read_text())
        src = doc.get("x-ucos-source", {})
        types = lint_asyncapi(p, src.get("boundedContext"), seen_types)
        n_aas += 1
        if src.get("id", "").startswith("DOM-"):
            dom = yaml.safe_load((DOMAINS / f"{src['id']}.yaml").read_text())
            missing = {e["type"] for e in dom.get("events") or []} - set(types)
            for t in sorted(missing):
                err(p, f"CR-006-001-02 DOM event '{t}' absent from AsyncAPI")
    for e in errors:
        print("LINT", e)
    if errors:
        print(f"FAILED — {len(errors)} contract lint errors")
        return 1
    print(f"contracts lint OK — {n_oas} OpenAPI, {n_aas} AsyncAPI, {len(seen_types)} event types")
    return 0


if __name__ == "__main__":
    sys.exit(main())
