#!/usr/bin/env python3
"""Generate language-neutral contracts from the vendored corpus (CIC-030-001 §5.1).

For every DOM-*.yaml with status `specified`, emits under contracts/<boundedContext>/:
  <DOM>.openapi.yaml   OpenAPI 3.1 — every REST api, operationIds = command/query names
  <DOM>.asyncapi.yaml  AsyncAPI 3.0 — every event type as a channel + send operation
Generated files carry x-ucos-source {id, version} and are never hand-edited; `--check` fails when the
committed files differ from a fresh generation (drift).

  gen_contracts.py           write
  gen_contracts.py --check   verify committed contracts are up to date
"""
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOMAINS = ROOT / "corpus/corpora/CORPUS-002-domain/domains"
OUT = ROOT / "contracts"
K = "../kernel/"
HEADER = "# GENERATED by tools/gen_contracts.py from {src} {ver} — do not edit; refine in a sibling *.refinement.yaml\n"

PRIMITIVES = {
    "string": {"type": "string"}, "text": {"type": "string"}, "int": {"type": "integer"},
    "integer": {"type": "integer"}, "long": {"type": "integer", "format": "int64"},
    "boolean": {"type": "boolean"}, "bool": {"type": "boolean"}, "json": {"type": "object"},
    "decimal": {"$ref": K + "decimal.schema.json"}, "Instant": {"type": "string", "format": "date-time"},
    "Date": {"type": "string", "format": "date"}, "duration": {"type": "string", "pattern": "^-?P"},
    "Duration": {"type": "string", "pattern": "^-?P"}, "uri": {"type": "string", "format": "uri"},
    "Sha256": {"type": "string", "pattern": "^(sha256:)?[0-9a-f]{64}$"},
    "SemVer": {"type": "string", "pattern": "^[0-9]+\\.[0-9]+\\.[0-9]+([-+].*)?$"},
    "CurrencyCode": {"type": "string", "pattern": "^[A-Z]{3}$|^X-[A-Z0-9-]+$"},
    "BCP47": {"type": "string", "pattern": "^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$"},
    "cron": {"type": "string"}, "CEL": {"type": "string", "x-ucos-language": "cel"},
    "Money": {"$ref": K + "money.schema.json"}, "Quantity": {"$ref": K + "quantity.schema.json"},
    "Interval": {"$ref": K + "interval.schema.json"}, "LocalizedText": {"$ref": K + "localized-text.schema.json"},
    "Ulid": {"$ref": K + "ulid.schema.json"}, "JsonSchema": {"type": "object", "x-ucos-kind": "json-schema"},
}
IDENT = re.compile(r"^[A-Za-z][A-Za-z0-9]*$")
ENUM = re.compile(r"^[a-z0-9][a-z0-9-]*(\s*\|\s*[a-z0-9][a-z0-9-]*)+$")


def split_top(s: str):
    """Split on commas not nested in (), [], {}, <>."""
    out, depth, cur = [], 0, []
    for ch in s:
        if ch in "([{<":
            depth += 1
        elif ch in ")]}>":
            depth -= 1
        if ch == "," and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        out.append("".join(cur).strip())
    return out


def type_schema(raw, known):
    """Map a corpus field type string to a JSON Schema fragment. Unmappable text is kept verbatim."""
    t = str(raw).strip()
    if t.endswith("?"):
        return type_schema(t[:-1], known)
    if t.endswith("[]"):
        return {"type": "array", "items": type_schema(t[:-2], known)}
    if t.startswith("[") and t.endswith("]"):
        inner = t[1:-1].strip()
        if inner.startswith("{"):
            return {"type": "array", "items": brace_object(inner, known)}
        return {"type": "array", "items": type_schema(inner, known)}
    if t.startswith("{") and t.endswith("}"):
        return brace_object(t, known)
    m = re.match(r"^map<\s*([^,>]+)\s*,\s*(.+)>$", t)
    if m:
        return {"type": "object", "additionalProperties": type_schema(m.group(2), known)}
    if t in PRIMITIVES:
        return dict(PRIMITIVES[t])
    if t.endswith("Urn") and IDENT.match(t):
        return {"$ref": K + "urn.schema.json", "x-ucos-urn-kind": t}
    if ENUM.match(t):
        return {"type": "string", "enum": [x.strip() for x in t.split("|")]}
    if IDENT.match(t) and t in known:
        return {"$ref": f"#/components/schemas/{t}"}
    return {"description": t, "x-ucos-type": t}


ALT = re.compile(r"^[A-Za-z][A-Za-z0-9]*(/[A-Za-z][A-Za-z0-9]*)+\??$")
UNNAMED_ENUM = re.compile(r"^[a-z0-9-]+(\|[a-z0-9-]+)+$")


def lower_camel(name):
    return name[0].lower() + name[1:]


def add_items(items, known, props, req, notes):
    """Add brace-list / entity-field items to an object schema (props/req mutated)."""
    for item in items:
        item = item.strip()
        if not item:
            continue
        if UNNAMED_ENUM.match(item):           # e.g. "debit|credit": a value set whose field name the corpus omits
            notes.append(item)
            continue
        if ALT.match(item):                    # e.g. "shipTo/serviceAddress?": alternative optional fields
            for alt in item.rstrip("?").split("/"):
                props.setdefault(alt, {"x-ucos-alternative-of": item.rstrip("?")})
            continue
        f = field(item, known)
        if not f:
            notes.append(item)
            continue
        name, schema, required = f
        if name[0].isupper():                  # embedded type reference, e.g. "{urn, TestVector}"
            schema = {**type_schema(name, known), **{k: v for k, v in schema.items() if k == "description"}}
            name = lower_camel(name)
        if name in props:
            continue
        props[name] = schema
        if required:
            req.append(name)


def field(spec, known):
    """Parse one brace-list item like `entries[] (summary)`, `basedOn?`, `ucosversion per subject`."""
    m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)(\[\])?(\?)?\s*(?::\s*(.*))?(.*)$", spec.strip(), re.S)
    if not m:
        return None
    name, arr, opt, typ, rest = m.groups()
    rest = (rest or "").strip()
    if typ:
        schema = type_schema(typ.strip().rstrip("?"), known)
        opt = opt or typ.strip().endswith("?")
    else:
        schema = {}
    if rest:
        schema["description"] = rest.strip("() ").strip()
    if arr:
        schema = {"type": "array", "items": schema or {}}
    return name, schema, not opt


def brace_object(text, known):
    inner = text.strip()
    if inner.startswith("{") and inner.endswith("}"):
        inner = inner[1:-1]
    props, req, notes = {}, [], []
    add_items(split_top(inner), known, props, req, notes)
    out = {"type": "object", "properties": props}
    if req:
        out["required"] = req
    if notes:
        out["x-ucos-unnamed"] = notes
    return out


def io_schema(text, known):
    """Command input / query output → schema."""
    t = str(text or "").strip()
    if not t:
        return {"type": "object"}
    if t.startswith("{"):
        return brace_object(t, known)
    if "+" in t:
        parts = [p.strip() for p in t.split("+")]
        return {"allOf": [io_schema(p, known) if not IDENT.match(p) or p in known or p[0].isupper() else
                          {"type": "object", "properties": {p: {}}, "required": [p]} for p in parts]}
    if t == "page":
        return {"$ref": K + "page.schema.json"}
    return type_schema(t, known)


def components(dom, known):
    comps = {}
    for agg in dom.get("aggregates") or []:
        props, req = {}, []
        for f in agg.get("fields") or []:
            s = type_schema(f.get("type", "string"), known)
            props[f["name"]] = s
            if not str(f.get("type", "")).strip().endswith("?"):
                req.append(f["name"])
        sch = {"type": "object", "properties": props, "x-ucos-identity": agg.get("identity"),
               "x-ucos-invariants": agg.get("invariants") or []}
        if req:
            sch["required"] = req
        comps[agg["name"]] = sch
    for ent in dom.get("entities") or []:
        # Rejoin items that YAML flow syntax split inside parentheses, then parse with the brace grammar.
        flds = split_top(", ".join(str(f) for f in ent.get("fields") or []))
        props, req, notes = {}, [], []
        add_items(flds, known, props, req, notes)
        sch = {"type": "object", "x-ucos-within": ent.get("within"), "properties": props}
        if req:
            sch["required"] = req
        if notes:
            sch["x-ucos-unnamed"] = notes
        comps[ent["name"]] = sch
    for vo in dom.get("valueObjects") or []:
        d = str(vo.get("definition", ""))
        if d.startswith("{"):
            sch = brace_object(d, known)
        elif d.startswith("["):
            sch = type_schema(d, known)
        else:
            sch = {"description": d}
        sch["x-ucos-value-object"] = True
        comps[vo["name"]] = sch
    return comps


def path_params(path):
    return re.findall(r"\{([A-Za-z0-9_]+)\}", path)


def openapi(dom):
    hdr = dom["header"]
    own = dom["ownership"]
    known = {a["name"] for a in dom.get("aggregates") or []} | {e["name"] for e in dom.get("entities") or []} \
        | {v["name"] for v in dom.get("valueObjects") or []}
    cmds = {c["name"]: c for c in dom.get("commands") or []}
    qrys = {q["name"]: q for q in dom.get("queries") or []}
    perms = (dom.get("security") or {}).get("permissions") or []
    read_perms = [p for p in perms if p.endswith(".read")]
    write_perms = [p for p in perms if not p.endswith(".read")]
    paths, grpc, seen_ops = {}, [], set()
    for api in dom.get("apis") or []:
        if api.get("style") != "REST":
            grpc.append(api)
            continue
        path = api["path"]
        item = paths.setdefault(path, {})
        for method, name in (api.get("methods") or {}).items():
            m = method.lower()
            is_cmd = name in cmds
            op_id = name if name not in seen_ops else f"{name}_{m}_{len(seen_ops)}"
            seen_ops.add(op_id)
            params = [{"name": p, "in": "path", "required": True, "schema": {"type": "string"}} for p in path_params(path)]
            params.append({"$ref": "#/components/parameters/UcosTenant"})
            params.append({"$ref": "#/components/parameters/Traceparent"})
            if is_cmd and m == "post":
                params.append({"$ref": "#/components/parameters/IdempotencyKey"})
            if is_cmd and (m in ("put", "patch", "delete") or ":" in path.rsplit("/", 1)[-1]):
                params.append({"$ref": "#/components/parameters/IfMatch"})
            op = {"operationId": op_id, "tags": [hdr["id"]],
                  "summary": name, "x-ucos-kind": "command" if is_cmd else "query" if name in qrys else "operation"}
            if is_cmd:
                c = cmds[name]
                op["x-ucos-emits"] = c.get("emits") or []
                if c.get("note"):
                    op["description"] = c["note"]
                if c.get("async"):
                    op["x-ucos-async"] = True
                body = io_schema(c.get("input"), known)
                ok = {"description": "Command accepted", "headers": {"ETag": {"schema": {"type": "string"}}},
                      "content": {"application/json": {"schema": {"$ref": K + "command-result.schema.json"}}}}
                op["responses"] = {"202" if c.get("async") else "200": ok}
                op["x-ucos-permission" if len(write_perms) == 1 else "x-ucos-permission-candidates"] = \
                    write_perms[0] if len(write_perms) == 1 else write_perms
            else:
                q = qrys.get(name, {})
                body = io_schema(q.get("input"), known) if m != "get" else None
                if m == "get" and q.get("input"):
                    inp = io_schema(q.get("input"), known)
                    for pname, ps in (inp.get("properties") or {}).items():
                        if pname not in path_params(path):
                            params.append({"name": pname, "in": "query", "required": False,
                                           "schema": ps if ps.get("type") in ("string", "integer", "boolean")
                                           else {"type": "string", "description": ps.get("description", "")}})
                op["responses"] = {"200": {"description": "Query result", "content": {
                    "application/json": {"schema": io_schema(q.get("output"), known) if q else {"type": "object"}}}}}
                if q.get("consistency"):
                    op["x-ucos-consistency"] = q["consistency"]
                op["x-ucos-permission"] = read_perms[0] if read_perms else (perms[0] if perms else None)
            if body is not None and m in ("post", "put", "patch"):
                op["requestBody"] = {"required": True, "content": {"application/json": {"schema": body}}}
            if api.get("note"):
                op["description"] = (op.get("description", "") + " " + api["note"]).strip()
            op["parameters"] = params
            op["responses"]["default"] = {"$ref": "#/components/responses/Problem"}
            if op.get("x-ucos-permission") is None:
                op.pop("x-ucos-permission", None)
            item[m] = op
    doc = {
        "openapi": "3.1.0",
        "info": {"title": f"{hdr['title']} — API", "version": hdr["version"],
                 "description": " ".join(str(dom.get("purpose", "")).split())},
        "x-ucos-source": {"id": hdr["id"], "version": hdr["version"], "boundedContext": own["boundedContext"],
                          "service": own.get("service")},
        "servers": [{"url": "/"}],
        "paths": paths,
        "components": {
            "schemas": components(dom, known),
            "parameters": {
                "UcosTenant": {"name": "UCOS-Tenant", "in": "header", "required": True,
                               "schema": {"type": "string", "pattern": "^[a-z][a-z0-9-]{1,62}$"}},
                "Traceparent": {"name": "traceparent", "in": "header", "required": False, "schema": {"type": "string"}},
                "IdempotencyKey": {"name": "Idempotency-Key", "in": "header", "required": True,
                                   "schema": {"type": "string", "minLength": 8, "maxLength": 128}},
                "IfMatch": {"name": "If-Match", "in": "header", "required": True, "schema": {"type": "string"}},
            },
            "responses": {"Problem": {"description": "RFC 9457 problem", "content": {
                "application/problem+json": {"schema": {"$ref": K + "problem.schema.json"}}}}},
        },
    }
    if grpc:
        doc["x-ucos-grpc"] = grpc
    return doc


def asyncapi(dom):
    hdr = dom["header"]
    own = dom["ownership"]
    known = {a["name"] for a in dom.get("aggregates") or []} | {v["name"] for v in dom.get("valueObjects") or []}
    channels, operations, messages = {}, {}, {}
    for ev in dom.get("events") or []:
        t = ev["type"]
        _, ctx, agg, name, ver = t.split(".")
        key = re.sub(r"[^A-Za-z0-9]", "_", t)
        payload = brace_object(ev["payload"], known) if str(ev.get("payload", "")).startswith("{") \
            else {"description": str(ev.get("payload", ""))}
        msg = {"name": t, "title": f"{agg} {name}", "contentType": "application/json",
               "headers": {"$ref": K + "cloudevent.schema.json"}, "payload": payload,
               "x-ucos-aggregate": agg}
        if ev.get("consumers"):
            msg["x-ucos-consumers"] = ev["consumers"]
        messages[key] = msg
        channels[key] = {"address": t, "messages": {key: {"$ref": f"#/components/messages/{key}"}}}
        operations[f"publish_{key}"] = {"action": "send", "channel": {"$ref": f"#/channels/{key}"},
                                       "messages": [{"$ref": f"#/channels/{key}/messages/{key}"}]}
    return {
        "asyncapi": "3.0.0",
        "info": {"title": f"{hdr['title']} — Events", "version": hdr["version"]},
        "x-ucos-source": {"id": hdr["id"], "version": hdr["version"], "boundedContext": own["boundedContext"]},
        "defaultContentType": "application/cloudevents+json",
        "channels": channels, "operations": operations, "components": {"messages": messages},
    }


class _NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def render(doc, src, ver):
    return HEADER.format(src=src, ver=ver) + yaml.dump(doc, Dumper=_NoAliasDumper, sort_keys=False,
                                                       allow_unicode=True, width=120)


def plan():
    registry = yaml.safe_load((DOMAINS / "registry.yaml").read_text())
    entries = registry["domains"] if isinstance(registry, dict) else registry
    files = {}
    for e in entries:
        if e.get("status") != "specified":
            continue
        dom = yaml.safe_load((DOMAINS / f"{e['id']}.yaml").read_text())
        ctx = dom["ownership"]["boundedContext"]
        h = dom["header"]
        files[OUT / ctx / f"{h['id']}.openapi.yaml"] = render(openapi(dom), h["id"], h["version"])
        if dom.get("events"):
            files[OUT / ctx / f"{h['id']}.asyncapi.yaml"] = render(asyncapi(dom), h["id"], h["version"])
    return files


def main(argv):
    files = plan()
    existing = {p for p in OUT.glob("*/DOM-*.yaml")}
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, c in files.items() if not p.exists() or p.read_text() != c]
        orphan = [str(p.relative_to(ROOT)) for p in existing - set(files)]
        for s in stale:
            print("drift:", s)
        for o in orphan:
            print("orphan:", o)
        if stale or orphan:
            print("contracts are out of date — run ./ucos gen")
            return 1
        print(f"contracts up to date — {len(files)} generated files")
        return 0
    for p in existing - set(files):
        p.unlink()
    for p, c in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(c)
    print(f"generated {len(files)} contract files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
