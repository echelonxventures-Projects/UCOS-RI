#!/bin/sh
# ucos-lite database roles (CIC-003-001 §5, CIC-014-001 §3). Passwords come from the compose environment.
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE ucos_owner LOGIN PASSWORD '${UCOS_OWNER_PASSWORD}' NOSUPERUSER NOBYPASSRLS;
GRANT CREATE ON DATABASE ${POSTGRES_DB} TO ucos_owner;
CREATE ROLE ucos_echo_app LOGIN PASSWORD '${UCOS_ECHO_APP_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_echo_relay LOGIN PASSWORD '${UCOS_ECHO_RELAY_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_kernel_app LOGIN PASSWORD '${UCOS_KERNEL_APP_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_kernel_relay LOGIN PASSWORD '${UCOS_KERNEL_RELAY_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_eventing_app LOGIN PASSWORD '${UCOS_EVENTING_APP_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_eventing_relay LOGIN PASSWORD '${UCOS_EVENTING_RELAY_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_identity_app LOGIN PASSWORD '${UCOS_IDENTITY_APP_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_identity_relay LOGIN PASSWORD '${UCOS_IDENTITY_RELAY_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_commerce_app LOGIN PASSWORD '${UCOS_COMMERCE_APP_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_commerce_relay LOGIN PASSWORD '${UCOS_COMMERCE_RELAY_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_supply_app LOGIN PASSWORD '${UCOS_SUPPLY_APP_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE ROLE ucos_supply_relay LOGIN PASSWORD '${UCOS_SUPPLY_RELAY_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA ucos_meta AUTHORIZATION ucos_owner;
SQL
